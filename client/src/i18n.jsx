const LanguageContext = createContext(null);
export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try { return localStorage.getItem("salon-language") === "st" ? "st" : "en"; }
    catch { return "en"; }
  });
  const setLanguage = (value) => {
    const next = value === "st" ? "st" : "en";
    setLanguageState(next);
    try { localStorage.setItem("salon-language", next); } catch { /* preference is optional */ }
  };
  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (text) => language === "st" ? (translations[text] || text) : text,
  }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
export function useLanguage() {
  return useContext(LanguageContext) || { language: "en", setLanguage: () => {}, t: (text) => text };
}
export function LanguageSwitcher() {
  const { language, setLanguage } = useLanguage();
  return <label className="language-switcher">
    <span className="visually-hidden">Language / Puo</span>
    <select aria-label="Language / Puo" value={language} onChange={(event) => setLanguage(event.target.value)}>
      <option value="en">English</option>
      <option value="st">Sesotho</option>
    </select>
  </label>;
}
